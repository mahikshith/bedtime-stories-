export const RHYMES: Rhyme[] = [...ORIGINAL, ...TRADITIONAL];

export const RHYME_BY_ID = new Map(RHYMES.map((r) => [r.id, r]));

export function getRhyme(id: string): Rhyme {
  const rhyme = RHYME_BY_ID.get(id);
  if (!rhyme) throw new Error(`Unknown rhyme: ${id}`);
  return rhyme;
}
