/**
 * The rhyme corpus.
 *
 * Two halves, deliberately:
 *
 *  - `traditional` — lyrics published before 1928 and therefore public domain in
 *    the US. Parents want the classics and familiarity is a feature. Note that
 *    only the WORDS are free: specific recordings and arrangements carry their
 *    own copyright, so every one of these is spoken by the device's own voice
 *    and no existing arrangement is reproduced.
 *
 *  - `original` — written for this app, which makes them the ownable asset.
 *    They carry {child} and {companion} slots, tie to the eighteen worlds, and
 *    are built to the recipe in docs/RESEARCH-PLATFORM.md §5: trochaic metre,
 *    rhyme words at line end, a refrain to join, a dropped final word to supply,
 *    actions to tap the beat, and enough nonsense to be funny.
 */

