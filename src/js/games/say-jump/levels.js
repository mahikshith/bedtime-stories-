const cache = new Map();

/** Parse a level on demand; parsed maps are immutable between plays so we
 *  deep-copy the mutable bits (crumble state, pickups) on every load. */
export function loadLevel(index) {
  const def = LEVELS[Math.max(0, Math.min(LEVELS.length - 1, index))];
  if (!cache.has(def.id)) cache.set(def.id, parseMap(def.map));
  const base = cache.get(def.id);
  return {
    ...def,
    index,
    ...base,
    platforms: base.platforms.map((p) => ({ ...p })),
    hazards: base.hazards.map((h) => ({ ...h })),
    pickups: base.pickups.map((p) => ({ ...p })),
    wordGates: base.wordGates.map((g) => ({ ...g })),
    props: base.props,
  };
}

