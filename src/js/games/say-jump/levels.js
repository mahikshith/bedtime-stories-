/**
 * Say & Jump — authored levels.
 *
 * Twelve hand-built levels across four worlds. Each one introduces exactly
 * one new idea and then gives the child three or four chances to use it
 * before the next level adds anything; that pacing is why the difficulty
 * curve holds for a five-year-old.
 *
 * Levels are PILLARS OVER WATER, not a flat floor with sky above it. On a
 * portrait phone a bottom-aligned floor pushes every platform off the bottom
 * of the frame, and a game about judging distance becomes unplayable because
 * the player cannot see what they are jumping to. Surfaces therefore live in
 * the middle band of the screen with water beneath them.
 *
 * Budgets, enforced by assertions in the composer:
 *
 *   charge 0.00 -> ~150px forward   (a nudge)
 *   charge 0.50 -> ~355px           (5 tiles)
 *   charge 1.00 -> ~560px           (7 tiles, a real shout)
 *   max apex     260px              (4 tiles of climb)
 *
 * Legend lives in core/tilemap.js.
 *
 * The map strings below are produced by tools/compose-levels.py, which does
 * the column arithmetic and asserts every ground gap stays inside the jump
 * budget. Edit the spec there and re-run it rather than nudging tiles here.
 */

